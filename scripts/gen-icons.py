#!/usr/bin/env python3
"""Regenerate the server icons from assets/desearch-logo-400.png.

Writes assets/icon-512.png, assets/icon-64.png, assets/favicon.ico and
icons-data.ts (base64 copies of the same bytes, so the Vercel functions serve
them without reading files). Run from the repo root after changing the logo:

    python3 scripts/gen-icons.py

Needs Pillow (pip install Pillow).
"""

import base64
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
SOURCE = ASSETS / "desearch-logo-400.png"
ICO_SIZES = [(16, 16), (32, 32), (48, 48), (64, 64)]


def resize(image: Image.Image, size: int) -> Image.Image:
    return image.resize((size, size), Image.Resampling.LANCZOS)


def main() -> None:
    logo = Image.open(SOURCE).convert("RGBA")

    resize(logo, 512).save(ASSETS / "icon-512.png", optimize=True)
    resize(logo, 64).save(ASSETS / "icon-64.png", optimize=True)
    resize(logo, 64).save(ASSETS / "favicon.ico", sizes=ICO_SIZES)

    entries = [
        ("ICON_512_PNG_BASE64", "icon-512.png"),
        ("ICON_64_PNG_BASE64", "icon-64.png"),
        ("FAVICON_ICO_BASE64", "favicon.ico"),
    ]
    lines = [
        "// Generated by scripts/gen-icons.py from assets/desearch-logo-400.png. Do not edit.",
        "",
    ]
    for name, filename in entries:
        encoded = base64.b64encode((ASSETS / filename).read_bytes()).decode("ascii")
        lines.append(f'export const {name}: string = "{encoded}";')
    (ROOT / "icons-data.ts").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
