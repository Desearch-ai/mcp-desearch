#!/usr/bin/env python3
"""Regenerate the server icons from assets/desearch-mark-white.png.

Writes public/icon-512.png, public/icon-64.png, public/favicon.png (the 64x64
icon), public/favicon.ico and icons-data.ts. Vercel serves the public/ files
as static assets, with the headers set in vercel.json. icons-data.ts holds
base64 copies of the same bytes, so the local HTTP server (http.ts) serves the
same icons without reading files.

The source glyph is assets/desearch-mark-white.png, which is byte-identical to
https://www.desearch.ai/logo.png (white on transparent). The www.desearch.ai
header shows the logo on a white bar with CSS brightness-0, which renders it
pure black. So each icon is the glyph in #000000 centered on an opaque #FFFFFF
square, matching the header. The header wordmark (logo-combined) is wide, so
only the square glyph is used. Every size is composed on its own from the
source glyph, which is only ever downscaled; no finished icon is resized into
another. Run from the repo root after changing the icon:

    python3 scripts/gen-icons.py

Needs only Pillow 10.1 or later (pip install pillow, in a venv).
"""

import base64
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parent.parent
ASSETS = ROOT / "assets"
PUBLIC = ROOT / "public"
SOURCE = ASSETS / "desearch-mark-white.png"
BACKGROUND = (0xFF, 0xFF, 0xFF, 255)
GLYPH_SCALE = 0.62  # larger glyph dimension as a fraction of the tile size
ICO_SIZES = [16, 32, 48, 64]


def black_glyph(source: Image.Image) -> Image.Image:
    # Same result as CSS brightness-0: RGB becomes 0, alpha is kept.
    glyph = Image.new("RGBA", source.size, (0, 0, 0, 0))
    glyph.putalpha(source.getchannel("A"))
    return glyph


def compose(glyph: Image.Image, size: int) -> Image.Image:
    image = Image.new("RGBA", (size, size), BACKGROUND)
    scale = GLYPH_SCALE * size / max(glyph.size)
    width = round(glyph.width * scale)
    height = round(glyph.height * scale)
    assert width <= glyph.width and height <= glyph.height, (
        f"glyph would be upscaled to {width}x{height} from {glyph.width}x{glyph.height}"
    )
    # RGB is constant black, so resizing the RGBA image directly is safe.
    mark = glyph.resize((width, height), Image.Resampling.LANCZOS)
    image.alpha_composite(mark, ((size - width) // 2, (size - height) // 2))
    return image


def main() -> None:
    glyph = black_glyph(Image.open(SOURCE).convert("RGBA"))
    PUBLIC.mkdir(exist_ok=True)

    compose(glyph, 512).save(PUBLIC / "icon-512.png")
    compose(glyph, 64).save(PUBLIC / "icon-64.png")
    # favicon.png is the same bytes as icon-64.png.
    (PUBLIC / "favicon.png").write_bytes((PUBLIC / "icon-64.png").read_bytes())

    # Pillow uses an appended image when its size matches an ICO entry, so
    # each entry is composed separately at its own size.
    frames = [compose(glyph, size) for size in ICO_SIZES]
    frames[-1].save(
        PUBLIC / "favicon.ico",
        sizes=[(size, size) for size in ICO_SIZES],
        append_images=frames[:-1],
    )

    entries = [
        ("ICON_512_PNG_BASE64", "icon-512.png"),
        ("ICON_64_PNG_BASE64", "icon-64.png"),
        ("FAVICON_ICO_BASE64", "favicon.ico"),
    ]
    lines = [
        "// Generated by scripts/gen-icons.py from assets/desearch-mark-white.png",
        "// (https://www.desearch.ai/logo.png). The site header renders it black on",
        "// white via CSS brightness-0, so the icon is the black glyph on white. Do not edit.",
        "",
    ]
    for name, filename in entries:
        encoded = base64.b64encode((PUBLIC / filename).read_bytes()).decode("ascii")
        lines.append(f'export const {name}: string = "{encoded}";')
    (ROOT / "icons-data.ts").write_text("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
